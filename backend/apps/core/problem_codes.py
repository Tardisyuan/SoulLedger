"""`ProblemCode`: every `code` a problem body may carry (apps/core/problems.py).

No Django imports, on purpose: pytest.ini names `UnknownProblemCode` in `filterwarnings`, and pytest resolves that
class before Django is configured.

`problems.body()` warns with `UnknownProblemCode` on a code outside this enum; pytest turns the warning into a
failure, so a test that reaches a new code fails until the code is added here. Production only warns.

The upper-case members are the death-sync integration's codes (`apps/death_sync/`), which external systems read
as they are; everything else is snake_case.
"""
