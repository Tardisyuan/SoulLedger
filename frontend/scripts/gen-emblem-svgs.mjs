// Writes src/generated/emblemSvgs.ts from public/v4/emblems-f/soulledger-emblem-<civ>-<dark|light>.svg
// (Design batch 24 version F, the inlay set: landing cards only; public/v4/emblems/ holds version G, the armillary sphere, for everything else).
// Run from anywhere: `node frontend/scripts/gen-emblem-svgs.mjs`. Rerun after Design delivers new emblems;
// underworldMap.test.ts fails while the module and the files differ.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "public", "v4", "emblems-f");
const entries = readdirSync(dir)
  .map((f) => f.match(/^soulledger-emblem-(\w+)-(dark|light)\.svg$/))
  .filter(Boolean)
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map((m) => `  ${JSON.stringify(`${m[1]}-${m[2]}`)}: ${JSON.stringify(readFileSync(path.join(dir, m[0]), "utf8"))},`);

writeFileSync(
  path.join(root, "src", "generated", "emblemSvgs.ts"),
  `// GENERATED by frontend/scripts/gen-emblem-svgs.mjs from public/v4/emblems-f/*-{dark,light}.svg. Do not edit.\n` +
    `// The landing cards render these inline so the first (server) frame already has the emblems.\n` +
    `export const EMBLEM_SVGS: Readonly<Record<string, string>> = {\n${entries.join("\n")}\n};\n`,
);
