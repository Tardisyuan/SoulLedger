/** The app may start Live Activities. */
function applyInfoPlist(plist) {
  plist.NSSupportsLiveActivities = true;
  return plist;
}

const quote = (v) => `"${v}"`;

/**
 * The extension's build settings, both configurations. Its versions must equal the app's (App Store rule);
 * the team is the app's, so a signed app signs its extension the same way (a free personal team can sign a
 * widget extension — it is App Groups and push it cannot, and this extension uses neither).
 */
function widgetBuildSettings({ bundleId, version, build, team, tablet }) {
  return {
    PRODUCT_NAME: quote("$(TARGET_NAME)"),
    PRODUCT_BUNDLE_IDENTIFIER: quote(bundleId),
    INFOPLIST_FILE: quote(`${TARGET}/${PLIST_FILE}`),
    SWIFT_VERSION: "5.0",
    IPHONEOS_DEPLOYMENT_TARGET: DEPLOYMENT_TARGET,
    TARGETED_DEVICE_FAMILY: quote(tablet ? "1,2" : "1"),
    MARKETING_VERSION: quote(version),
    CURRENT_PROJECT_VERSION: quote(build),
    CODE_SIGN_STYLE: "Automatic",
    ...(team ? { DEVELOPMENT_TEAM: team } : {}),
    SKIP_INSTALL: "YES",
    CLANG_ENABLE_MODULES: "YES",
    SWIFT_EMIT_LOC_STRINGS: "YES",
    LD_RUNPATH_SEARCH_PATHS: quote("$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"),
  };
}

